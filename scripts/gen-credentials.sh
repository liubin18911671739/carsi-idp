#!/usr/bin/env bash
# =============================================================================
# CARSI IdP 凭据首启生成器（一次性，幂等）
#   生成到 ./credentials/，此后必须持久化并备份 —— 一旦重新生成，
#   所有已对接 SP 拿到的 metadata 全部失效（EntityID 里的证书指纹变了）。
#
#   用法:  ./scripts/gen-credentials.sh
#   前置:  cp .env.example .env 并填好 IDP_HOSTNAME / *_PASSWORD / *_SALT
# =============================================================================
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$(pwd)"

# ── 读 .env ──────────────────────────────────────────────────────────────────
if [[ ! -f .env ]]; then
  echo "✗ 缺少 .env —— 先执行: cp .env.example .env 并填写" >&2
  exit 1
fi
set -a; source .env; set +a

: "${IDP_HOSTNAME:?IDP_HOSTNAME 未设置}"
: "${SEALER_STORE_PASSWORD:?SEALER_STORE_PASSWORD 未设置}"
: "${SEALER_KEY_PASSWORD:?SEALER_KEY_PASSWORD 未设置}"
: "${BACKCHANNEL_KEYSTORE_PASSWORD:?BACKCHANNEL_KEYSTORE_PASSWORD 未设置}"
: "${PERSISTENT_ID_SALT:?PERSISTENT_ID_SALT 未设置}"

IMAGE="cscfi/shibboleth-idp:5.2.2"
CRED_DIR="$ROOT/credentials"
mkdir -p "$CRED_DIR"

if [[ -f "$CRED_DIR/idp-signing.crt" && -f "$CRED_DIR/idp-encryption.crt" ]]; then
  echo "✓ 凭据已存在（$CRED_DIR），跳过生成。"
  echo "  如需重签（会作废所有 SP 对接）请先手动备份并删除该目录下的 idp-*.crt/.key。"
  exit 0
fi

echo "▶ 为 $IDP_HOSTNAME 生成凭据（容器内 keygen.sh，一次性）..."

# keygen.sh 参数（已从镜像内 --help 实测）:
#   --hostname 证书 CN | --dnsAltName SAN | --uriAltName SAN URI
#   --certfile/--keyfile 输出路径 | --size 3072 | --lifetime 20(年)
CERTSH='set -e
IDP=/opt/shibboleth-idp
KG=$IDP/bin/keygen.sh
H="'"$IDP_HOSTNAME"'"

# 1) 签名证书
$KG --hostname "$H" --dnsAltName "$H" \
    --uriAltName "https://$H/idp/shibboleth" \
    --certfile  $IDP/credentials/idp-signing.crt \
    --keyfile   $IDP/credentials/idp-signing.key \
    --size 3072 --lifetime 20
echo "  ✓ idp-signing"

# 2) 加密证书（同一 CN，独立密钥对）
$KG --hostname "$H" --dnsAltName "$H" \
    --uriAltName "https://$H/idp/shibboleth" \
    --certfile  $IDP/credentials/idp-encryption.crt \
    --keyfile   $IDP/credentials/idp-encryption.key \
    --size 3072 --lifetime 20
echo "  ✓ idp-encryption"

# 3) backchannel p12（Jetty 内部信任用）
$KG --hostname "$H" --dnsAltName "$H" \
    --storefile $IDP/credentials/idp-backchannel.p12 \
    --storepass "'"$BACKCHANNEL_KEYSTORE_PASSWORD"'" \
    --storetype PKCS12 --size 3072 --lifetime 20
echo "  ✓ idp-backchannel.p12"
'

docker run --rm \
  -u 0:0 \
  -v "$CRED_DIR":/opt/shibboleth-idp/credentials \
  --entrypoint bash \
  "$IMAGE" -c "$CERTSH"

# ── secrets.properties（口令集中处，供 entrypoint 与 IdP 读取）──────────────
# 注意: entrypoint 用 `source <(grep '^idp.sealer*' ...)` 并 strip 空格和点，
#       口令中不可含空格或 "."，否则变量名会解析错。
cat > "$CRED_DIR/secrets.properties" <<EOF
# Generated by gen-credentials.sh — DO NOT COMMIT, DO NOT REGENERATE
# Access to internal AES encryption key
idp.sealer.storePassword = $SEALER_STORE_PASSWORD
idp.sealer.keyPassword = $SEALER_KEY_PASSWORD

# Password for idp-backchannel.p12
idp.backchannel.keyStorePassword = $BACKCHANNEL_KEYSTORE_PASSWORD

# Jetty TLS keystore（反代终止 TLS 时可不用；ENABLE_SSL=1 时需要）
JETTY_KEYSTORE_PASSWORD = ${JETTY_KEYSTORE_PASSWORD:-ChangeMeJettyTLS2026}

# Salt used to generate persistent/pairwise IDs, must be kept secret
idp.persistentId.salt = $PERSISTENT_ID_SALT
EOF
chmod 600 "$CRED_DIR/secrets.properties"

# ── sealer.jks + sealer.kver（entrypoint 也会生成，这里提前生成以保证一致）──
docker run --rm -u 0:0 \
  -v "$CRED_DIR":/opt/shibboleth-idp/credentials \
  --entrypoint bash "$IMAGE" -c "
set -e
/opt/shibboleth-idp/bin/seckeygen.sh \
  --storefile /opt/shibboleth-idp/credentials/sealer.jks \
  --storepass '$SEALER_STORE_PASSWORD' \
  --versionfile /opt/shibboleth-idp/credentials/sealer.kver \
  --alias secret
echo '  ✓ sealer.jks / sealer.kver'
"

echo
echo "✓ 凭据生成完毕 → $CRED_DIR"
ls -l "$CRED_DIR"
echo
echo "⚠ 立即备份 $CRED_DIR 到离线位置；它一旦丢失/重生成，全部 SP 须重换 metadata。"
